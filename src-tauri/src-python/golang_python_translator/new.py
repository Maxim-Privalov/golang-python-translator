from __future__ import annotations

from typing import List


def main() -> None:
    x = 10
    y = 20
    faa: List[int] = []
    print(fa(x, y))
    print(faa)


def fa(x: int, y: int) -> int:
    if x < y:
        return x
    return y


if __name__ == "__main__":
    main()
